#!/usr/bin/env python3
"""English translations of the theme and Core strings.

    tools/i18n-build.py            write the WordPress PHP translation files from tools/i18n/en_US.json
    tools/i18n-build.py --check    also list front-end msgids in the code that have no English yet

Source of truth: tools/i18n/en_US.json = {"seohouse": {arabic msgid: english}, "seohouse-core": {...}}.
Output (loaded by WordPress 6.5+ for the en_US locale, i.e. on /en/ pages with Polylang):
    wordpress/themes/seohouse/languages/en_US.l10n.php                (load_theme_textdomain naming)
    wordpress/plugins/seohouse-core/languages/seohouse-core-en_US.l10n.php
Arabic needs no file: the msgids are the Arabic text.
"""
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "tools", "i18n", "en_US.json")
OUT = {
    "seohouse": os.path.join(REPO, "wordpress/themes/seohouse/languages/en_US.l10n.php"),
    "seohouse-core": os.path.join(REPO, "wordpress/plugins/seohouse-core/languages/seohouse-core-en_US.l10n.php"),
}
ROOTS = {
    "seohouse": os.path.join(REPO, "wordpress/themes/seohouse"),
    "seohouse-core": os.path.join(REPO, "wordpress/plugins/seohouse-core/inc"),
}
# files whose strings are only seen in wp-admin / WP-CLI (they stay Arabic)
ADMIN_ONLY = re.compile(
    r"(inc/release-files\.php|inc/dependencies\.php|inc/setup\.php|importer/.*|seo-transfer\.php|settings-tools\.php|"
    r"admin-cleanup\.php|migrate-posts\.php|schema-check\.php|acf\.php|fields/|remote\.php|content-transfer\.php|"
    r"reviews\.php|platforms\.php|media\.php|rankmath\.php|post-types\.php|i18n\.php)$"
)
CALL = re.compile(r"\b(?:__|_e|esc_html__|esc_html_e|esc_attr__|esc_attr_e|_x|esc_html_x|esc_attr_x)\(\s*'((?:[^'\\]|\\.)*)'\s*,\s*(?:'[^']*'\s*,\s*)?'(seohouse(?:-core)?)'\s*\)")
AR = re.compile(r"[؀-ۿ]")


def php_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def write(domain, messages):
    lines = [
        "<?php",
        "// Generated by tools/i18n-build.py from tools/i18n/en_US.json — edit the JSON, not this file.",
        "return array(",
        "\t'domain' => " + php_str(domain) + ",",
        "\t'language' => 'en_US',",
        "\t'plural-forms' => 'nplurals=2; plural=(n != 1);',",
        "\t'messages' => array(",
    ]
    for k in sorted(messages):
        lines.append("\t\t" + php_str(k) + " => " + php_str(messages[k]) + ",")
    lines += ["\t),", ");", ""]
    os.makedirs(os.path.dirname(OUT[domain]), exist_ok=True)
    open(OUT[domain], "w", encoding="utf-8").write("\n".join(lines))


def code_msgids(domain):
    found = {}
    for base, _, files in os.walk(ROOTS[domain]):
        for f in files:
            if not f.endswith(".php"):
                continue
            p = os.path.join(base, f)
            rel = os.path.relpath(p, REPO)
            if ADMIN_ONLY.search(rel):
                continue
            for m in CALL.finditer(open(p, encoding="utf-8").read()):
                if m.group(2) == domain and AR.search(m.group(1)):
                    found.setdefault(m.group(1).replace("\\'", "'"), rel)
    return found


def main():
    data = json.load(open(SRC, encoding="utf-8"))
    for domain in OUT:
        msgs = {k: v for k, v in data.get(domain, {}).items() if isinstance(v, str) and v and not AR.search(v)}
        write(domain, msgs)
        print(f"{domain}: {len(msgs)} strings → {os.path.relpath(OUT[domain], REPO)}")
    if "--check" in sys.argv:
        missing = 0
        for domain in OUT:
            have = data.get(domain, {})
            admin = set(data.get("_admin_only", []))  # seen only by editors in wp-admin: stay Arabic
            for msgid, rel in sorted(code_msgids(domain).items(), key=lambda x: x[1]):
                if not have.get(msgid) and msgid not in admin:
                    missing += 1
                    print(f"MISSING {domain} {rel}: {msgid}")
        print(f"missing: {missing}")
        sys.exit(1 if missing else 0)


main()
